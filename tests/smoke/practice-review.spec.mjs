import {test, expect} from '@playwright/test';
import crypto from 'node:crypto';
import fs from 'node:fs';
const baseURL=process.env.SMOKE_BASE_URL || 'http://127.0.0.1:5005';

test('F3 精确差异、保存失败保护、采纳拒绝撤销、实际复测与刷新回看', async({page})=>{
    test.skip(process.env.F3_LIVE_AI!=='1','Explicit opt-in for one real model response');
    test.setTimeout(180000);
    const username='review_'+crypto.randomBytes(4).toString('hex'),password=crypto.randomBytes(16).toString('hex');
    expect((await page.request.post(baseURL+'/api/register',{data:{username,email:username+'@example.test',password}})).status()).toBe(201);
    await page.request.post(baseURL+'/api/login',{data:{username,password}});
    const errors=[]; page.on('pageerror',error=>errors.push(error.message));
    await page.setViewportSize({width:1440,height:1080});
    await page.goto(baseURL+'/practice.html?problem=DEMO-01');
    await expect(page.locator('#helpMode')).toBeEnabled();
    const original='n = int(input())\ntotal = 0\nfor i in range(1, n):\n    total += i\nprint(total)\n';
    await page.locator('#codeInput').fill(original);
    await page.locator('#submitBtn').click();
    await expect(page.locator('#evidenceSummary')).toContainText('Wrong Answer',{timeout:15000});
    const helpResponse=page.waitForResponse(r=>/\/submissions\/\d+\/help$/.test(r.url())&&r.request().method()==='POST',{timeout:80000});
    await page.locator('[data-help-level="3"]').click();
    const help=await (await helpResponse).json(); expect(help.success,JSON.stringify(help.error)).toBeTruthy();
    expect(help.data.proposal).toBeTruthy(); const p=help.data.proposal;
    fs.mkdirSync('tmp/f3-check',{recursive:true});
    fs.writeFileSync('tmp/f3-check/live-proposal.json',JSON.stringify(help.data,null,2));
    const card=page.locator('#diagnosisContent [data-proposal-card]').first();
    await card.locator(':scope > summary').click();
    await expect(card.locator('.review-diff').first()).toContainText('range(1, n)');
    await expect(card.locator('[data-proposal-action="undo"]')).toBeHidden();
    await card.locator('[data-proposal-action="reject"]').click();
    await expect(card.locator('[data-proposal-status]')).toContainText('已拒绝');
    await expect(page.locator('#codeInput')).toHaveValue(original);
    await page.route('**/api/proposals/*/actions',route=>route.fulfill({status:503,json:{success:false,error:{message:'操作未保存，请重试'}}}),{times:1});
    await card.locator('[data-proposal-action="accept"]').click();
    await expect(card.locator('.review-message')).toContainText('未保存');
    await expect(page.locator('#codeInput')).toHaveValue(original);
    await card.locator('[data-proposal-action="accept"]').click();
    await expect(page.locator('#codeInput')).toHaveValue(p.candidate_code);
    await page.locator('#codeInput').fill(p.candidate_code+'# 后续编辑\n');
    await expect(card.locator('[data-proposal-action="undo"]')).toBeDisabled();
    await page.locator('#codeInput').fill(p.candidate_code);
    await card.locator('[data-proposal-action="undo"]').click();
    await expect(page.locator('#codeInput')).toHaveValue(original);
    await card.locator('[data-proposal-action="accept"]').click();
    await expect(page.locator('#codeInput')).toHaveValue(p.candidate_code);
    await page.reload();
    await expect(page.locator('#codeInput')).toHaveValue(p.candidate_code);
    await expect(page.locator('#practiceReview')).toBeVisible();
    await page.locator('#practiceReview > summary').click();
    await expect(page.locator('#practiceTimeline')).toContainText('撤销');
    await expect(page.locator('#practiceTimeline')).toContainText('拒绝');
    // Submitting a different program must retain its actual failing result and attribution.
    await page.locator('#codeInput').fill(p.candidate_code+'\nprint(0)\n');
    await page.locator('#submitBtn').click();
    await expect(page.locator('#evidenceSummary')).toContainText('Wrong Answer');
    await expect(page.locator('#practiceTimeline')).toContainText('采纳后代码又有修改');
    const finalCode=p.candidate_code+'\n# 复查后保留的版本\n';
    await page.locator('#codeInput').fill(finalCode);
    await page.locator('#submitBtn').click();
    await expect(page.locator('#evidenceSummary')).toContainText('Accepted',{timeout:15000});
    await expect(page.locator('#practiceTimeline')).toContainText('通过当前 3 个用例');
    const history=await (await page.request.get(baseURL+'/api/problems/DEMO-01/practice-history')).json();
    fs.writeFileSync('tmp/f3-check/history.json',JSON.stringify(history.data,null,2));
    const last=history.data.submissions[0]; expect(last.code).toBe(finalCode);
    const event=history.data.events.find(e=>e.submission_id===last.submission_id&&e.kind==='retest');
    expect(event.proposal_id).toBe(p.id); expect(event.data.edited_after_accept).toBe(true);
    await page.reload();
    await page.locator('#practiceReview > summary').click();
    await expect(page.locator('#practiceTimeline')).toContainText('通过当前 3 个用例');
    await expect(page.locator('#codeInput')).toHaveValue(finalCode);
    const savedStatus=page.locator('#practiceTimeline [data-proposal-status]').first();
    await expect(savedStatus).toContainText('这份代码通过当前 3 个用例');
    await page.locator('#codeInput').fill(finalCode+'# 未复测的改动\n');
    await expect(savedStatus).toContainText('尚未复测');
    await page.locator('#codeInput').fill(finalCode);
    await page.screenshot({path:'tmp/f3-check/history-desktop.png',fullPage:true});
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:'tmp/f3-check/history-mobile.png',fullPage:true});
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBeTruthy();
    expect(errors).toEqual([]);
});
