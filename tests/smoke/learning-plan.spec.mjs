import {test,expect} from '@playwright/test';
import fs from 'node:fs';
const base=process.env.SMOKE_BASE_URL||'http://127.0.0.1:5007';
test('问卷保存、推荐简单项目、真实交付及进度回显',async({page})=>{
  test.setTimeout(120000);
  let aiCalls=0;const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.route('**/api/ai_learning_analysis_stream',r=>{aiCalls++;return r.fulfill({status:503,json:{success:false,error:{message:'AI forbidden in automatic recommendation tests'}}});});
  await page.route('**/api/task-room/projects/*/messages',r=>r.fulfill({status:503,json:{success:false,error:{message:'AI forbidden in this test'}}}));
  expect((await page.request.post(base+'/api/login',{data:{username:'task-browser',password:'test-password'}})).ok()).toBeTruthy();
  const questions=(await (await page.request.get(base+'/api/learning-plan/questions')).json()).data.questions;
  await page.setViewportSize({width:1440,height:1000});
  await page.goto(base+'/learn-analytics.html');
  await expect(page.locator('#questionLoading')).toBeHidden();
  if(await page.locator('#retakeBtn').isVisible()) await page.locator('#retakeBtn').click();
  await expect(page.locator('.option-btn').first()).toBeEnabled();
  await page.locator('#nextBtn').click();
  await expect(page.locator('#questionError')).toContainText('选择');
  for(let i=0;i<questions.length;i++){
    await expect(page.locator('#currentQuestionTitle')).toHaveText(questions[i].title);
    await page.locator(`.option-btn[data-value="${questions[i].options[0].value}"]`).click();
    if(i<questions.length-1) await page.locator('#nextBtn').click();
  }
  const submitted=page.waitForResponse(r=>new URL(r.url()).pathname==='/api/learning-plan'&&r.request().method()==='POST');
  await page.locator('#submitBtn').click();
  const response=await submitted;expect(response.status()).toBe(200);
  const plan=(await response.json()).data.plan;
  expect(plan.recommendations[0].level).toBe('starter');
  await expect(page.locator('.recommendation-card')).toHaveCount(6);
  await page.reload();
  await expect(page.locator('#assessmentForm')).toBeHidden();
  await expect(page.locator('.recommendation-card')).toHaveCount(6);
  await page.screenshot({path:'tmp/task-room-check/learning-recommendations.png',fullPage:true});
  const first=plan.recommendations[0];
  await page.locator('.recommendation-card').filter({has:page.getByRole('heading',{name:first.title,exact:true})}).locator('.project-action').click();
  await expect(page.locator('#scenario-dialog')).toBeVisible();
  await expect(page.locator('#scenario-preview')).toContainText(first.title);
  const creating=page.waitForResponse(r=>new URL(r.url()).pathname==='/api/task-room/projects'&&r.request().method()==='POST');
  await page.locator('#create-project').click();
  expect((await creating).status()).toBe(201);
  const freezing=page.waitForResponse(r=>r.url().endsWith('/freeze'));
  await page.locator('#freeze-contract').click();
  const project=(await (await freezing).json()).data.project;
  const references=JSON.parse(fs.readFileSync('tmp/task-room-check/references.json','utf8'));
  const match=references.find(r=>r.scenario_id===project.scenario_id&&Object.entries(r.rules).every(([k,v])=>project.contract.rules[k]===v));
  expect(match).toBeTruthy();
  await page.locator('#code-editor').fill(match.code);
  const running=page.waitForResponse(r=>r.url().endsWith('/run'));
  await page.locator('#run-acceptance').click();
  const run=(await (await running).json()).data.run;
  expect(run.status).toBe('passed');expect(run.execution.execution_backend).toBe('docker');expect(run.total).toBe(6);
  const delivering=page.waitForResponse(r=>r.url().endsWith('/deliver'));
  await page.locator('#deliver-project').click();expect((await delivering).status()).toBe(200);
  await page.locator('header nav a[href="/learn-analytics.html"]').click();
  await expect(page.locator('.recommendation-card')).toHaveCount(6);
  const completed=page.locator('.recommendation-card').filter({has:page.getByRole('heading',{name:first.title,exact:true})});
  await expect(completed.locator('.project-status')).toHaveText('已交付');
  await expect(completed.locator('.project-action')).toHaveText(/回看交付/);
  expect(await completed.locator('.project-action').getAttribute('href')).toContain(project.id);
  await page.locator('#refreshPlanBtn').click();
  await expect(completed.locator('.project-status')).toHaveText('已交付');
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBeTruthy();
  await page.screenshot({path:'tmp/task-room-check/learning-plan-mobile.png',fullPage:true});
  expect(aiCalls).toBe(0);expect(errors).toEqual([]);
});

test('访客可填写，问卷加载失败可重试，未提交不会产生学习结论',async({page})=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  let fail=true;
  await page.route('**/api/learning-plan/questions',r=>fail?r.fulfill({status:503,json:{success:false,error:{message:'测试网络错误'}}}):r.continue());
  await page.goto(base+'/learn-analytics.html');
  await expect(page.locator('#retryQuestionsBtn')).toBeVisible();
  fail=false;await page.locator('#retryQuestionsBtn').click();
  await expect(page.locator('.option-btn').first()).toBeEnabled();
  await expect(page.locator('#pathPreview')).toBeHidden();
  await page.locator('.option-btn').first().click();
  await page.reload();await expect(page.locator('.option-btn').first()).toHaveAttribute('aria-pressed','true');
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBeTruthy();
  expect(errors).toEqual([]);
});
